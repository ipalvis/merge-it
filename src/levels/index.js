/* Levels: one folder each under src/levels/, found automatically. A folder holds
     level.js    settings and wording (its key is the folder name; `order` places it on the map switch)
     map.json   generated by `npm run build:map <key>` from the folder's source.mjs; don't hand-edit
   The game plays one level per page load: the one the URL names (?map=eu), else the last one played, else the
   first. Only that level's map data is downloaded. The map switch in the top bar reloads with ?map= set. */
const configs = import.meta.glob('./*/level.js', { eager: true, import: 'default' });
const maps = import.meta.glob('./*/map.json', { import: 'default' });

export const LEVELS = Object.fromEntries(
  Object.entries(configs)
    .map(([path, L]) => ({ ...L, key: path.split('/')[1] }))
    .sort((a, b) => a.order - b.order)
    .map(L => [L.key, L]),
);
export const LEVEL_KEY = 'merge-it-level'; // localStorage: the last map played
let last = null;
try {
  last = localStorage.getItem(LEVEL_KEY);
} catch (e) {}
const level = LEVELS[new URLSearchParams(location.search).get('map')] ?? LEVELS[last] ?? Object.values(LEVELS)[0];
try {
  localStorage.setItem(LEVEL_KEY, level.key);
} catch (e) {}
export const MAP = { ...level, data: await maps[`./${level.key}/map.json`]() };
